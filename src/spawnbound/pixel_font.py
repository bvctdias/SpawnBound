HEIGHT = 7
SPACING = 1


def normalize(text: str) -> str:
    stripped = unicodedata.normalize("NFKD", text)
    return "".join(c for c in stripped if not unicodedata.combining(c)).upper()


class PixelFont:
    def __init__(self) -> None:
        self._cache: dict[tuple, pygame.Surface] = {}

    def size(self, text: str, scale: int = 1) -> tuple[int, int]:
        text = normalize(text)
        if not text:
            return 0, HEIGHT * scale
        width = sum(len(GLYPHS.get(c, GLYPHS["?"])[0]) for c in text) + SPACING * (len(text) - 1)
        return width * scale, HEIGHT * scale

    def render(self, text: str, color: tuple[int, int, int], scale: int = 1,
               shadow: tuple[int, int, int] | None = None) -> pygame.Surface:
        key = (text, tuple(color), scale, None if shadow is None else tuple(shadow))
        surface = self._cache.get(key)
        if surface is not None:
            return surface
        width, height = self.size(text, 1)
        extra = 1 if shadow is not None else 0
        base = pygame.Surface((max(1, width + extra), height + extra), pygame.SRCALPHA)
        layers = ((shadow, 1),) if shadow is not None else ()
        for layer_color, offset in (*layers, (color, 0)):
            x = 0
            for char in normalize(text):
                glyph = GLYPHS.get(char, GLYPHS["?"])
                for row, line in enumerate(glyph):
                    for column, pixel in enumerate(line):
                        if pixel == "#":
                            base.set_at((x + column + offset, row + offset), layer_color)
                x += len(glyph[0]) + SPACING
        surface = base if scale == 1 else pygame.transform.scale(
            base, (base.get_width() * scale, base.get_height() * scale))
        if len(self._cache) > 512:
            self._cache.clear()
        self._cache[key] = surface
        return surface
