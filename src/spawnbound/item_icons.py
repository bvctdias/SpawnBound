def _seared(drawing: str, flesh: str) -> str:
    rows = drawing.strip("\n").splitlines()
    return "\n".join("".join("m" if p in flesh and (x - y) % 4 == 0 else p for x, p in enumerate(row))
                     for y, row in enumerate(rows))


