def _paint(drawing: str, palette: dict[str, str]) -> pygame.Surface:
    rows = drawing.strip("\n").splitlines()
    canvas = pygame.Surface((16, 16), pygame.SRCALPHA)
    top = (16 - len(rows)) // 2
    filled = set()
    for y, row in enumerate(rows, top):
        for x, pixel in enumerate(row):
            if pixel != ".":
                canvas.set_at((x, y), INK if pixel == "#" else palette[pixel])
                filled.add((x, y))
    for x, y in filled:
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if (nx, ny) not in filled and 0 <= nx < 16 and 0 <= ny < 16:
                canvas.set_at((nx, ny), INK)
    return canvas


@lru_cache(maxsize=None)
def icon(item: str, scale: int = 2) -> pygame.Surface:
    _, palette, drawing = ITEMS[item]
    return pygame.transform.scale(_paint(drawing, palette), (16 * scale, 16 * scale))


@lru_cache(maxsize=None)
def mini_icon(item: str) -> pygame.Surface:
    return pygame.transform.scale(icon(item, 1), (24, 24))


@lru_cache(maxsize=None)
def held_tool(item: str) -> pygame.Surface:
    _, palette, drawing = HELD[item]
    return _paint(drawing, palette)


